/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
    mongoose_init();

    mongoose_set_http_handlers("IMU_data", my_get_IMU_data, my_set_IMU_data);

    TickType_t last_wake_time = xTaskGetTickCount();
    const TickType_t delay = pdMS_TO_TICKS(100); // 100ms interval

    for (;;) {
        // Poll Mongoose (handle incoming HTTP requests)
        mongoose_poll();


         int16_t accel_x = myIMU_ReadAccelX();
         int16_t accel_y = myIMU_ReadAccelY();
         int16_t accel_z = myIMU_ReadAccelZ();
         float timestamp = HAL_GetTick() / 1000.0f;

        vTaskDelayUntil(&last_wake_time, delay);
    }


  /* USER CODE END 5 */
}

