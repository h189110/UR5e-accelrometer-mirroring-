void MMA8451_Init(void)
 {
     uint8_t Data;
     // 1. Standby Mode: Clear Active bit (Bit 0) in CTRL_REG1
     Data = 0x00;
     HAL_I2C_Mem_Write(&hi2c1, MMA8451_ADDRESS, MMA8451_CTRL_REG1, 1, &Data, 1, HAL_MAX_DELAY);

     // 2. Configure: Set Scale (2g range) in XYZ_DATA_CFG
     Data = 0x00; // Full Scale 2g (bits Fs1:Fs0 = 00)
     HAL_I2C_Mem_Write(&hi2c1, MMA8451_ADDRESS, MMA8451_XYZ_DATA_CFG, 1, &Data, 1, HAL_MAX_DELAY);

     // 3. Active Mode: Set Active bit (Bit 0) in CTRL_REG1
     Data = 0x01; // ODR=800Hz (default), Active Mode (Bit 0 = 1)
     HAL_I2C_Mem_Write(&hi2c1, MMA8451_ADDRESS, MMA8451_CTRL_REG1, 1, &Data, 1, HAL_MAX_DELAY);
 }

int16_t myIMU_ReadAccelX(void) {
  uint8_t RxData[2];
  HAL_I2C_Mem_Read(&hi2c1, MMA8451_ADDRESS, MMA8451_OUT_X_MSB, 1, RxData, 2, HAL_MAX_DELAY);
  return (int16_t)((RxData[0] << 8) | RxData[1]) >> 2;
}

int16_t myIMU_ReadAccelY(void) {
  uint8_t RxData[2];
  HAL_I2C_Mem_Read(&hi2c1, MMA8451_ADDRESS, MMA8451_OUT_X_MSB + 2, 1, RxData, 2, HAL_MAX_DELAY);
  return (int16_t)((RxData[0] << 8) | RxData[1]) >> 2;
}

int16_t myIMU_ReadAccelZ(void) {
  uint8_t RxData[2];
  HAL_I2C_Mem_Read(&hi2c1, MMA8451_ADDRESS, MMA8451_OUT_X_MSB + 4, 1, RxData, 2, HAL_MAX_DELAY);
  return (int16_t)((RxData[0] << 8) | RxData[1]) >> 2;
}


